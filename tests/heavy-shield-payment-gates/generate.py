#!/usr/bin/env python3
"""Extract UpdatePaymentGates verbatim from the real baseline/candidate sources.

The legacy method fixture is pinned by SHA256; the candidate method is read from
the repository product source. Generated shells compile both actual bodies with
the same native/payment boundary stubs. Whole-file scope is checked by Git/IL review.
"""
import argparse
import hashlib
import json
import pathlib
import re
import sys

ANCHOR = re.compile(r"private\s+static\s+void\s+UpdatePaymentGates\s*\(\s*\)")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def extract_method(text: str, label: str):
    matches = list(ANCHOR.finditer(text))
    if len(matches) != 1:
        raise SystemExit(f"{label}: expected exactly 1 UpdatePaymentGates anchor, got {len(matches)}")
    m = matches[0]
    brace = text.find("{", m.end())
    if brace < 0:
        raise SystemExit(f"{label}: no opening brace after anchor")
    depth = 0
    i = brace
    state = "code"
    while i < len(text):
        c = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""
        if state == "code":
            if c == "/" and nxt == "/":
                state = "line"; i += 2; continue
            if c == "/" and nxt == "*":
                state = "block"; i += 2; continue
            if c == '"':
                # verbatim strings do not occur in the target; keep the scanner simple and strict.
                state = "string"; i += 1; continue
            if c == "'":
                state = "char"; i += 1; continue
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    end = i + 1
                    break
            i += 1
        elif state == "line":
            if c == "\n":
                state = "code"
            i += 1
        elif state == "block":
            if c == "*" and nxt == "/":
                state = "code"; i += 2; continue
            i += 1
        elif state == "string":
            if c == "\\":
                i += 2; continue
            if c == '"':
                state = "code"
            i += 1
        elif state == "char":
            if c == "\\":
                i += 2; continue
            if c == "'":
                state = "code"
            i += 1
    else:
        raise SystemExit(f"{label}: unbalanced braces")
    start_line = text.count("\n", 0, m.start())
    end_line = text.count("\n", 0, end)
    method = text[m.start():end]
    if not method.rstrip().endswith("}"):
        raise SystemExit(f"{label}: extracted slice does not end with a closing brace")
    if "point?.Payable" not in method or "forceBlockPayment" not in method:
        raise SystemExit(f"{label}: extracted slice lacks expected body markers")
    return method, start_line, end_line


def shell_source(namespace: str, method: str) -> str:
    return f"""// <auto-generated> Extracted verbatim from the real source by generate.py.
// Do not edit; re-run the extractor instead.
using Fixture.Model;

namespace {namespace}
{{
internal static class Shell
{{
{method}

    internal static Point[] _points;
    internal static long _shopLife;
    internal static bool _economyFault;
    internal static bool _retiring;
    internal static bool _menuSuspended;

    private static bool BowUsable() => Box.BowUsable();
    private static bool AnyBusy() => Box.AnyBusy(_points);
    private static bool CanPay(int index, long life, Player player) => Box.CanPay(index, life, player);

    internal static void RunForTest() => UpdatePaymentGates();
}}
}}
"""


def main() -> int:
    here = pathlib.Path(__file__).resolve().parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidate-source", type=pathlib.Path,
                    default=here.parents[1] / "il2cpp" / "HeavyShieldShopShell.cs")
    ap.add_argument("--generated-dir", type=pathlib.Path, default=here / "Generated")
    args = ap.parse_args()
    baseline_path = here / "BaselineUpdatePaymentGates.cs.txt"
    base_method, _, _ = extract_method(baseline_path.read_text(encoding="utf-8"), "legacy fixture")
    expected = "a96d4e464764c54891a9a075ecc6e24bc59611925561ad5ee5757f7626aeea6a"
    if sha256(base_method.encode("utf-8")) != expected:
        raise SystemExit("legacy method fixture SHA mismatch")
    candidate_path = args.candidate_source.resolve()
    cand_bytes = candidate_path.read_bytes()
    cand_method, cand_start, cand_end = extract_method(cand_bytes.decode("utf-8"), "product candidate")
    outdir = args.generated_dir.resolve()
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "BaselineShell.g.cs").write_text(shell_source("Fixture.Baseline", base_method), encoding="utf-8")
    (outdir / "CandidateShell.g.cs").write_text(shell_source("Fixture.Candidate", cand_method), encoding="utf-8")
    record = {"baselineSliceSHA256": expected,
              "candidateSourceSHA256": sha256(cand_bytes),
              "candidateSliceSHA256": sha256(cand_method.encode("utf-8")),
              "candidateSliceLines": [cand_start + 1, cand_end],
              "sliceIdentical": base_method == cand_method,
              "scope": "Actual method bodies only; whole-file changes require Git/assembly review"}
    (outdir / "slices.json").write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(record, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
