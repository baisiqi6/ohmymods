// Compilation shell: copies the H3 preparation decision surface byte-for-byte from a single
// in-memory snapshot of each current production file. It also emits immutable digest constants
// that are compiled into the test assembly, so a stale test DLL cannot claim new source identity.
// This tool deliberately knows nothing about the behaviour of the extracted code.
using System;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

internal static class Program
{
    private const string FieldsStartMarker = "private static string? _hookOwner;";
    private const string FieldsEndMarker = "private static long _captureSequence;";
    private const string MethodMarker = "PrepareAtPlaying(Game game, Kingdom kingdom)";
    private const string ProxyMarker = "=> PalacePaidHandle.Engine.PrepareAtPlaying(game,kingdom);";
    private const string CallerMarker = "if (_paidPreparationGame != managers.game.Pointer)";
    private const string DeadlineMarker = "_deadline = Time.unscaledTime + 20f;";
    private const string ProbeStartMarker = "float now = Time.unscaledTime;";
    private const string ProbeEndMarker = "_nextProbe = now + 0.25f;";

    private static readonly UTF8Encoding StrictUtf8 = new UTF8Encoding(false, true);

    private sealed class SourceSnapshot
    {
        internal readonly string Path;
        internal readonly byte[] Bytes;
        internal readonly string Text;
        internal readonly string Sha256;

        internal SourceSnapshot(string path)
        {
            Path = path;
            Bytes = File.ReadAllBytes(path); // The only disk read for this source.
            Text = StrictUtf8.GetString(Bytes);
            Sha256 = Hash(Bytes);
        }
    }

    private static int Main(string[] args)
    {
        if (args.Length != 3)
            throw new ArgumentException("Usage: Extractor <paid-source.cs> <visible-source.cs> <output-directory>");
        string paidPath = args[0], visiblePath = args[1], output = args[2];
        Directory.CreateDirectory(output);

        // One raw-byte snapshot per source; extraction and every digest use that snapshot.
        var paid = new SourceSnapshot(paidPath);
        var visible = new SourceSnapshot(visiblePath);

        string fields = ExtractFields(paid.Text);
        string method = ExtractMethod(paid.Text);
        string proxy = ExtractProxy(paid.Text);
        string caller = ExtractCaller(visible.Text);
        string deadline = ExtractDeadline(visible.Text);
        string probe = ExtractProbe(visible.Text);

        string engineSource =
            "// <auto-generated>Extracted verbatim from il2cpp/Patch_PalacePaidResponsibility.cs." + "\n" +
            "// Do not edit; regenerate through the test project build.</auto-generated>\n" +
            "#nullable enable\n" +
            "using System;\n\n" +
            "namespace KingdomEnhancedMod\n" +
            "{\n" +
            "internal sealed partial class PalacePaidHandle\n" +
            "{\n" +
            "internal static partial class Engine\n" +
            "{\n" +
            "#pragma warning disable CS0414\n" +
            fields + "\n" +
            "#pragma warning restore CS0414\n\n" +
            method + "\n" +
            "}\n" +
            "}\n\n" +
            "internal static partial class PalacePaidResponsibility\n" +
            "{\n" +
            proxy + "\n" +
            "}\n" +
            "}\n";
        string callerSource =
            "// <auto-generated>Extracted verbatim from il2cpp/Patch_PalaceVisibleEntry.cs." + "\n" +
            "// Do not edit; regenerate through the test project build.</auto-generated>\n" +
            "#nullable enable\n" +
            "using System;\n\n" +
            "namespace KingdomEnhancedMod\n" +
            "{\n" +
            "internal sealed partial class HostScene\n" +
            "{\n" +
            "    internal void Tick(Managers managers)\n" +
            "    {\n" +
            "        TickCalls++;\n" +
            "        HostFixture.CurrentScene = this;\n" +
            caller + "\n" +
            "        PostPaidPrepareReached++;\n" +
            "    }\n" +
            "}\n" +
            "}\n";
        byte[] engineBytes = StrictUtf8.GetBytes(engineSource);
        byte[] callerBytes = StrictUtf8.GetBytes(callerSource);

        var metadata = new
        {
            schema = 2,
            paidSourceSha256 = paid.Sha256,
            paidSourceBytes = paid.Bytes.Length,
            visibleSourceSha256 = visible.Sha256,
            visibleSourceBytes = visible.Bytes.Length,
            fields = TextMetadata("Engine.fields", fields),
            methods = new[]
            {
                TextMetadata("Engine.PrepareAtPlaying", method),
                TextMetadata("PalacePaidResponsibility.PrepareAtPlaying", proxy),
                TextMetadata("PalaceVisibleEntry.paidPrepareBlock", caller)
            },
            windows = new[]
            {
                TextMetadata("deadline20s", deadline),
                TextMetadata("probe025s", probe)
            },
            generated = new[]
            {
                ByteMetadata("PalacePaidPreparation.Extracted.cs", engineBytes),
                ByteMetadata("PalacePaidPreparation.Caller.cs", callerBytes)
            }
        };
        byte[] metadataBytes = StrictUtf8.GetBytes(
            JsonSerializer.Serialize(metadata, new JsonSerializerOptions { WriteIndented = true }) + "\n");
        string metadataSha = Hash(metadataBytes);

        WriteBytes(Path.Combine(output, "PalacePaidPreparation.Extracted.cs"), engineBytes);
        WriteBytes(Path.Combine(output, "PalacePaidPreparation.Caller.cs"), callerBytes);
        WriteBytes(Path.Combine(output, "extraction.json"), metadataBytes);

        string digests =
            "// <auto-generated>Compiled identity snapshot; do not edit.</auto-generated>\n" +
            "namespace KingdomEnhancedMod\n" +
            "{\n" +
            "internal static class PalacePaidPreparationDigests\n" +
            "{\n" +
            "    internal const int Schema = 2;\n" +
            "    internal const string PaidSourceSha256 = \"" + paid.Sha256 + "\";\n" +
            "    internal const int PaidSourceBytes = " + paid.Bytes.Length + ";\n" +
            "    internal const string VisibleSourceSha256 = \"" + visible.Sha256 + "\";\n" +
            "    internal const int VisibleSourceBytes = " + visible.Bytes.Length + ";\n" +
            "    internal const string FieldsSha256 = \"" + TextSha(fields) + "\";\n" +
            "    internal const int FieldsChars = " + fields.Length + ";\n" +
            "    internal const string EngineMethodSha256 = \"" + TextSha(method) + "\";\n" +
            "    internal const int EngineMethodChars = " + method.Length + ";\n" +
            "    internal const string ProxySha256 = \"" + TextSha(proxy) + "\";\n" +
            "    internal const int ProxyChars = " + proxy.Length + ";\n" +
            "    internal const string CallerSha256 = \"" + TextSha(caller) + "\";\n" +
            "    internal const int CallerChars = " + caller.Length + ";\n" +
            "    internal const string DeadlineSha256 = \"" + TextSha(deadline) + "\";\n" +
            "    internal const int DeadlineChars = " + deadline.Length + ";\n" +
            "    internal const string ProbeSha256 = \"" + TextSha(probe) + "\";\n" +
            "    internal const int ProbeChars = " + probe.Length + ";\n" +
            "    internal const string GeneratedEngineSha256 = \"" + Hash(engineBytes) + "\";\n" +
            "    internal const int GeneratedEngineBytes = " + engineBytes.Length + ";\n" +
            "    internal const string GeneratedCallerSha256 = \"" + Hash(callerBytes) + "\";\n" +
            "    internal const int GeneratedCallerBytes = " + callerBytes.Length + ";\n" +
            "    internal const string MetadataSha256 = \"" + metadataSha + "\";\n" +
            "    internal const int MetadataBytes = " + metadataBytes.Length + ";\n" +
            "}\n" +
            "}\n";
        WriteBytes(Path.Combine(output, "PalacePaidPreparation.Digests.cs"), StrictUtf8.GetBytes(digests));

        Console.WriteLine("snapshot paidBytes=" + paid.Bytes.Length + " paidSha=" + paid.Sha256
            + " visibleBytes=" + visible.Bytes.Length + " visibleSha=" + visible.Sha256);
        Console.WriteLine("extracted fields=" + fields.Length + " method=" + method.Length
            + " proxy=" + proxy.Length + " caller=" + caller.Length
            + " deadline=" + deadline.Length + " probe=" + probe.Length
            + " engineBytes=" + engineBytes.Length + " callerBytes=" + callerBytes.Length
            + " metadataBytes=" + metadataBytes.Length + " metadataSha=" + metadataSha);
        return 0;
    }

    private static object TextMetadata(string name, string text) => new
    {
        name,
        sha256 = TextSha(text),
        chars = text.Length
    };

    private static object ByteMetadata(string name, byte[] bytes) => new
    {
        name,
        sha256 = Hash(bytes),
        bytes = bytes.Length
    };

    private static void WriteBytes(string path, byte[] bytes) => File.WriteAllBytes(path, bytes);

    private static string TextSha(string text) => Hash(StrictUtf8.GetBytes(text));

    private static string Hash(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();

    private static int LineStart(string source, int index)
    {
        int newline = source.LastIndexOf('\n', index);
        return newline < 0 ? 0 : newline + 1;
    }

    private static int LineEnd(string source, int start)
    {
        int end = source.IndexOf('\n', start);
        if (end < 0) end = source.Length;
        if (end > start && source[end - 1] == '\r') end--;
        return end;
    }

    private static int FindLine(string source, string marker, bool excludeArrow)
    {
        int from = 0;
        while (true)
        {
            int index = source.IndexOf(marker, from, StringComparison.Ordinal);
            if (index < 0) throw new InvalidOperationException("Production marker missing: " + marker);
            int start = LineStart(source, index);
            int end = LineEnd(source, start);
            if (!excludeArrow || !source.Substring(start, end - start).Contains("=>", StringComparison.Ordinal))
                return start;
            from = end;
        }
    }

    private static string SliceLine(string source, int start) => source.Substring(start, LineEnd(source, start) - start);

    private static string ExtractFields(string source)
    {
        int start = FindLine(source, FieldsStartMarker, false);
        int end = LineEnd(source, FindLine(source, FieldsEndMarker, false));
        return source.Substring(start, end - start);
    }

    private static string ExtractMethod(string source)
    {
        int start = FindLine(source, MethodMarker, true);
        int open = FindCodeChar(source, start, '{');
        int end = BalancedEnd(source, open);
        return source.Substring(start, end - start + 1);
    }

    private static string ExtractProxy(string source) => SliceLine(source, FindLine(source, ProxyMarker, false));

    private static string ExtractCaller(string source)
    {
        int start = FindLine(source, CallerMarker, false);
        int open = FindCodeChar(source, start, '{');
        int end = BalancedEnd(source, open);
        return source.Substring(start, end - start + 1);
    }

    private static string ExtractDeadline(string source) => SliceLine(source, FindLine(source, DeadlineMarker, false));

    private static string ExtractProbe(string source)
    {
        int start = FindLine(source, ProbeStartMarker, false);
        int last = FindLine(source, ProbeEndMarker, false);
        int end = LineEnd(source, last);
        return source.Substring(start, end - start);
    }

    // Locate the first code brace at/after start while skipping comments and literals.
    private static int FindCodeChar(string source, int start, char wanted)
    {
        for (int i = start; i < source.Length; i++)
        {
            char c = source[i];
            if (!TrySkip(source, ref i, out bool isCode) || !isCode) continue;
            if (c == wanted) return i;
        }
        throw new InvalidOperationException("Code character not found: " + wanted);
    }

    private static int BalancedEnd(string source, int open)
    {
        int depth = 0;
        for (int i = open; i < source.Length; i++)
        {
            if (!TrySkip(source, ref i, out bool isCode) || !isCode) continue;
            char c = source[i];
            if (c == '{') depth++;
            else if (c == '}')
            {
                depth--;
                if (depth == 0) return i;
            }
        }
        throw new InvalidOperationException("Unbalanced production block");
    }

    // Returns false for a skipped character (the loop advances i). isCode says whether
    // the current character is ordinary code or a comment delimiter.
    private static bool TrySkip(string source, ref int i, out bool isCode)
    {
        isCode = true;
        char c = source[i];
        if (c == '/' && i + 1 < source.Length && source[i + 1] == '/')
        {
            i = source.IndexOf('\n', i + 2);
            if (i < 0) i = source.Length;
            isCode = false;
            return false;
        }
        if (c == '/' && i + 1 < source.Length && source[i + 1] == '*')
        {
            int close = source.IndexOf("*/", i + 2, StringComparison.Ordinal);
            if (close < 0) throw new InvalidOperationException("Unterminated block comment");
            i = close + 1;
            isCode = false;
            return false;
        }
        if (c == '"' || c == '\'')
        {
            char quote = c;
            bool verbatim = quote == '"' && i > 0 && source[i - 1] == '@';
            i++;
            while (i < source.Length)
            {
                if (verbatim && source[i] == '"' && i + 1 < source.Length && source[i + 1] == '"') { i += 2; continue; }
                if (!verbatim && source[i] == '\\') { i += 2; continue; }
                if (source[i] == quote) break;
                i++;
            }
            if (i >= source.Length) throw new InvalidOperationException("Unterminated literal");
            isCode = false;
            return false;
        }
        return true;
    }
}
