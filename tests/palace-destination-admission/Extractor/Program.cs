// Compilation shell: copies the two admission decision methods byte-for-byte from the
// current production file. This tool deliberately knows nothing about their behaviour.
using System;
using System.Collections.Generic;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

internal static class Program
{
    private const string ClassMarker = "internal static class PalaceDestinationAdmission";
    private const string FieldsStartMarker = "    private const float Tolerance";
    private const string FieldsEndMarker = "    private static IntPtr _prepareGame, _prepareGlobal, _prepareCampaign;";
    private const string DescribeMarker = "    internal static bool TryDescribeDestination(";
    private const string PrepareMarker = "    internal static void NoteDestinationPrepare(";

    private static int Main(string[] args)
    {
        if (args.Length != 2)
            throw new ArgumentException("Usage: Extractor <production-source.cs> <output-directory>");
        // One raw-byte snapshot for decoding, extraction and every digest. Never re-read the file.
        byte[] sourceBytes = File.ReadAllBytes(args[0]);
        string source = new UTF8Encoding(false, true).GetString(sourceBytes);
        string output = args[1];
        Directory.CreateDirectory(output);

        int classIndex = Find(source, ClassMarker);
        string fields = SliceFields(source);
        string describe = SliceMethod(source, DescribeMarker);
        string prepare = SliceMethod(source, PrepareMarker);
        string sourceSha = Hash(sourceBytes);
        string fieldsSha = Hash(Encoding.UTF8.GetBytes(fields));
        string describeSha = Hash(Encoding.UTF8.GetBytes(describe));
        string prepareSha = Hash(Encoding.UTF8.GetBytes(prepare));

        string generated =
            "// <auto-generated>Extracted verbatim from il2cpp/Patch_PalaceDestinationSupport.cs." + "\n" +
            "// Do not edit; regenerate through the test project build.</auto-generated>\n" +
            "using System;\n" +
            "namespace KingdomEnhancedMod\n" +
            "{\n" +
            "internal static class PalaceAdmissionSourceIdentity\n" +
            "{\n" +
            "    internal const string SourceSha256 = \"" + sourceSha + "\";\n" +
            "    internal const string FieldsSha256 = \"" + fieldsSha + "\";\n" +
            "    internal const string DescribeSha256 = \"" + describeSha + "\";\n" +
            "    internal const string PrepareSha256 = \"" + prepareSha + "\";\n" +
            "    internal const int DescribeChars = " + describe.Length + ";\n" +
            "    internal const int PrepareChars = " + prepare.Length + ";\n" +
            "}\n" +
            "internal static partial class PalaceDestinationAdmission\n" +
            "{\n" +
            fields + "\n\n" +
            describe + "\n\n" +
            prepare + "\n" +
            "}\n" +
            "}\n";
        File.WriteAllText(Path.Combine(output, "PalaceDestinationAdmission.Extracted.cs"), generated, new UTF8Encoding(false));

        var metadata = new
        {
            schema = 1,
            source = "il2cpp/Patch_PalaceDestinationSupport.cs",
            sourceSha256 = sourceSha,
            fieldsSha256 = fieldsSha,
            methods = new[]
            {
                new { name = "TryDescribeDestination", sha256 = describeSha, chars = describe.Length },
                new { name = "NoteDestinationPrepare", sha256 = prepareSha, chars = prepare.Length }
            }
        };
        File.WriteAllText(Path.Combine(output, "extraction.json"),
            JsonSerializer.Serialize(metadata, new JsonSerializerOptions { WriteIndented = true }) + "\n",
            new UTF8Encoding(false));
        Console.WriteLine("extracted classAt=" + classIndex + " methods=" + describe.Length + "/" + prepare.Length
            + " source=" + metadata.sourceSha256);
        return 0;
    }

    private static object MethodMetadata(string name, string text) => new
    {
        name,
        sha256 = Hash(Encoding.UTF8.GetBytes(text)),
        chars = text.Length
    };

    private static string Hash(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();

    private static int Find(string source, string marker)
    {
        int index = source.IndexOf(marker, StringComparison.Ordinal);
        if (index < 0) throw new InvalidOperationException("Production marker missing: " + marker);
        return index;
    }

    private static string SliceFields(string source)
    {
        int start = Find(source, FieldsStartMarker);
        int endMarker = Find(source, FieldsEndMarker);
        int lineEnd = source.IndexOf('\n', endMarker);
        if (lineEnd < 0) throw new InvalidOperationException("Unterminated cache-field block");
        return source[start..lineEnd].TrimEnd('\r');
    }

    private static string SliceMethod(string source, string marker)
    {
        int start = Find(source, marker);
        int open = FindCodeChar(source, start, '{');
        int end = BalancedEnd(source, open);
        return source[start..(end + 1)];
    }

    // Locate the first code brace at/after start while skipping comments and literals.
    private static int FindCodeChar(string source, int start, char wanted)
    {
        for (int i = start; i < source.Length; i++)
        {
            char c = source[i];
            if (!TrySkip(source, ref i, out bool isCode) || !isCode) continue;
            if (c == wanted) return i;
        }
        throw new InvalidOperationException("Code character not found: " + wanted);
    }

    private static int BalancedEnd(string source, int open)
    {
        int depth = 0;
        for (int i = open; i < source.Length; i++)
        {
            if (!TrySkip(source, ref i, out bool isCode) || !isCode) continue;
            char c = source[i];
            if (c == '{') depth++;
            else if (c == '}')
            {
                depth--;
                if (depth == 0) return i;
            }
        }
        throw new InvalidOperationException("Unbalanced production block");
    }

    // Returns false for a skipped character (the loop advances i). isCode says whether
    // the current character is ordinary code or a comment delimiter.
    private static bool TrySkip(string source, ref int i, out bool isCode)
    {
        isCode = true;
        char c = source[i];
        if (c == '/' && i + 1 < source.Length && source[i + 1] == '/')
        {
            i = source.IndexOf('\n', i + 2);
            if (i < 0) i = source.Length;
            isCode = false;
            return false;
        }
        if (c == '/' && i + 1 < source.Length && source[i + 1] == '*')
        {
            int close = source.IndexOf("*/", i + 2, StringComparison.Ordinal);
            if (close < 0) throw new InvalidOperationException("Unterminated block comment");
            i = close + 1;
            isCode = false;
            return false;
        }
        if (c == '"' || c == '\'')
        {
            char quote = c;
            bool verbatim = quote == '"' && i > 0 && source[i - 1] == '@';
            i++;
            while (i < source.Length)
            {
                if (verbatim && source[i] == '"' && i + 1 < source.Length && source[i + 1] == '"') { i += 2; continue; }
                if (!verbatim && source[i] == '\\') { i += 2; continue; }
                if (source[i] == quote) break;
                i++;
            }
            if (i >= source.Length) throw new InvalidOperationException("Unterminated literal");
            isCode = false;
            return false;
        }
        return true;
    }
}
