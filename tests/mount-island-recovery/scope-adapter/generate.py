#!/usr/bin/env python3
"""Generate source-linked extraction from actual production; normal build always runs this."""
from pathlib import Path
import hashlib
import os

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent.parent
NEW = Path(os.environ.get("SCOPE_SOURCE_OVERRIDE", REPO / "il2cpp/Patch_MountIslandRecovery.cs"))
PLAN = REPO / "il2cpp/Patch_MountIslandRecoveryPlan.cs"
OLD = HERE / "baseline/Patch_MountIslandRecovery.0919.cs"


def extract(text, start_marker, method_marker):
    start = text.index(start_marker)
    method_at = text.index(method_marker, start)
    end = text.index("\n    /// <summary>", method_at)
    return text[start:end]


def main():
    new_text = NEW.read_text()
    plan_text = PLAN.read_text()
    old_text = OLD.read_text()
    new_body = extract(new_text, "    private enum ScopeReadPhase",
                       "private static bool TryReadScope(ScopeReadPhase")
    old_body = extract(old_text, "    /// <summary>读当前 scope",
                       "private static bool TryReadScope(int selectedExpected")
    s = plan_text.index("internal readonly struct MountIslandRecoveryScope")
    e = plan_text.index("\n/// <summary>\n/// 保存 WorldData", s)
    scope = plan_text[s:e]
    new_body = new_body.replace("private enum ScopeReadPhase", "internal enum ScopeReadPhase")
    new_body = new_body.replace("private static bool TryReadScope", "internal static bool TryReadScope")
    old_body = old_body.replace("TryReadScope", "OldTryReadScope").replace("private static bool", "internal static bool")
    digest = hashlib.sha256(NEW.read_bytes()).hexdigest()
    out = (
        "// <auto-generated>Source-linked extraction; regenerated by normal build.</auto-generated>\n"
        "using System;\nusing System.Collections.Generic;\nnamespace ScopeAdapter\n{\n"
        f"internal static class SourceAdapterGenerated {{ internal const string ProductionSource = @\"{NEW}\"; internal const string ProductionSHA256 = \"{digest}\"; }}\n"
        "internal static partial class MountIslandRecoveryRuntime\n{\n" + new_body + "\n}\n"
        "internal static partial class OldMountIslandRecoveryRuntime\n{\n" + old_body + "\n}\n"
        + scope + "\n}\n"
    )
    target = HERE / "ExtractedScope.cs"
    target.write_text(out)
    print("wrote", target, len(out), digest)


if __name__ == "__main__":
    main()
